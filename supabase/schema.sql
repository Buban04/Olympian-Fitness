-- Políticas básicas para el frontend.
create policy "usuarios leen su perfil" on public.usuarios
for select using (id = auth.uid() or public.mi_rol() = 'admin');

create policy "usuario actualiza su perfil" on public.usuarios
for update using (id = auth.uid() or public.mi_rol() = 'admin');

create policy "planes visibles" on public.planes
for select using (true);

create policy "horarios visibles" on public.horario_gimnasio
for select using (true);

create policy "entrenadores visibles" on public.entrenadores
for select using (true);

create policy "clientes ven sus membresias" on public.membresias
for select using (usuario_id = auth.uid() or public.mi_rol() = 'admin');

create policy "clientes crean membresia" on public.membresias
for insert with check (usuario_id = auth.uid());

create policy "rutinas visibles al dueño" on public.rutinas
for select using (
  usuario_id = auth.uid()
  or public.mi_rol() in ('admin','entrenador')
);

create policy "ejercicios visibles" on public.rutina_ejercicios
for select using (
  exists (
    select 1 from public.rutinas r
    where r.id = rutina_id
      and (r.usuario_id = auth.uid() or public.mi_rol() in ('admin','entrenador'))
  )
);

create policy "foro temas visibles" on public.foro_temas
for select using (true);

create policy "usuarios crean temas" on public.foro_temas
for insert with check (usuario_id = auth.uid());

create policy "foro respuestas visibles" on public.foro_respuestas
for select using (true);

create policy "usuarios responden" on public.foro_respuestas
for insert with check (usuario_id = auth.uid());

create policy "asistencias propias" on public.historial_asistencias
for select using (usuario_id = auth.uid() or public.mi_rol() = 'admin');

