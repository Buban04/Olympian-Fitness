create extension if not exists pgcrypto;

create table if not exists public.roles (
  id bigint generated by default as identity primary key,
  nombre varchar(30) unique not null
);

insert into public.roles (id, nombre) values
  (1, 'admin'), (2, 'entrenador'), (3, 'usuario')
on conflict (id) do update set nombre = excluded.nombre;

create table if not exists public.usuarios (
  id uuid primary key references auth.users(id) on delete cascade,
  nombre_completo varchar(150) not null,
  correo varchar(150) unique not null,
  telefono varchar(30),
  rol_id bigint not null references public.roles(id) default 3,
  activo boolean not null default true,
  fecha_registro timestamptz not null default now()
);

create table if not exists public.entrenadores (
  id bigint generated by default as identity primary key,
  usuario_id uuid unique not null references public.usuarios(id) on delete cascade,
  especialidad varchar(150) not null,
  descripcion text
);

create table if not exists public.planes (
  id bigint generated by default as identity primary key,
  nombre varchar(100) not null,
  precio numeric(10,2) not null,
  beneficios text not null,
  destacado boolean not null default false
);

create table if not exists public.membresias (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references public.usuarios(id) on delete cascade,
  plan_id bigint not null references public.planes(id),
  fecha_inicio date not null,
  fecha_fin date not null,
  estado varchar(20) not null default 'activa' check (estado in ('activa','vencida','cancelada')),
  metodo_pago varchar(30) not null default 'efectivo',
  referencia_pago varchar(100),
  detalle_pago varchar(150)
);

create table if not exists public.citas (
  id bigint generated by default as identity primary key,
  entrenador_id bigint not null references public.entrenadores(id) on delete cascade,
  cliente_id uuid references public.usuarios(id) on delete set null,
  fecha date not null,
  hora_inicio time not null,
  hora_fin time not null,
  estado varchar(20) not null default 'disponible' check (estado in ('disponible','confirmado','cancelado'))
);

create table if not exists public.horario_gimnasio (
  id bigint generated by default as identity primary key,
  dias varchar(100) not null,
  apertura time not null,
  cierre time not null,
  telefono varchar(30)
);

create table if not exists public.rutinas (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references public.usuarios(id) on delete cascade,
  entrenador_id bigint references public.entrenadores(id) on delete set null,
  nombre varchar(150) not null,
  duracion_min integer,
  descripcion text,
  fecha_creacion timestamptz not null default now()
);

create table if not exists public.rutina_ejercicios (
  id bigint generated by default as identity primary key,
  rutina_id bigint not null references public.rutinas(id) on delete cascade,
  dia varchar(30) not null,
  ejercicio varchar(150) not null,
  series integer,
  repeticiones varchar(30),
  notas varchar(200),
  orden integer not null default 0
);

create table if not exists public.foro_temas (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references public.usuarios(id) on delete cascade,
  titulo varchar(200) not null,
  contenido text not null,
  fecha_creacion timestamptz not null default now()
);

create table if not exists public.foro_respuestas (
  id bigint generated by default as identity primary key,
  tema_id bigint not null references public.foro_temas(id) on delete cascade,
  usuario_id uuid not null references public.usuarios(id) on delete cascade,
  contenido text not null,
  fecha_creacion timestamptz not null default now()
);

create table if not exists public.historial_asistencias (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references public.usuarios(id) on delete cascade,
  fecha date not null,
  hora_entrada time not null,
  hora_salida time,
  actividad varchar(100) not null
);

